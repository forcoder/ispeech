/**
 * 一组同主题颜文字。
 *
 * @param name 分类短名（如「开心」「动物」）；页标题由
 *   [T9Layouts.kaomojiPages] 拼成 `颜·分类名`，避免和表情页标题重名
 * @param symbols 该分类下的颜文字字面量，直接写成字符串，无需码点拼装
 */
